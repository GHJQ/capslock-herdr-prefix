# Linux: point Caps Lock at an F-key with a user XKB option, applied through
# GNOME's input-source settings. Sourced by bin/remap and uninstall.sh.
#
# There's no hidutil on Linux. The closest thing that needs neither root nor a
# daemon is a custom XKB option: libxkbcommon (1.0+) reads rules and symbols
# from ~/.config/xkb, and mutter compiles the keymap from the options GNOME
# stores in org.gnome.desktop.input-sources. That setting persists across logins,
# so there's no LaunchAgent equivalent to install.
#
# One option per F-key (herdr:caps_f12, herdr:caps_f13, ...) rather than one
# option whose symbols we rewrite: switching keys then changes the option list,
# which is what makes GNOME recompile the keymap.

XKB_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/xkb"
XKB_SYMBOLS="$XKB_DIR/symbols/herdr"
XKB_RULES="$XKB_DIR/rules/evdev"
XKB_MARKER="capslock-herdr-prefix"
GNOME_SCHEMA="org.gnome.desktop.input-sources"

gnome_available() {
  command -v gsettings >/dev/null 2>&1 &&
    gsettings get "$GNOME_SCHEMA" xkb-options >/dev/null 2>&1
}

xkb_write_files() {
  mkdir -p "$XKB_DIR/symbols" "$XKB_DIR/rules"

  {
    echo "// Generated by $XKB_MARKER: Caps Lock sends an F-key so herdr can bind it."
    i=1
    while [ "$i" -le 20 ]; do
      echo "partial modifier_keys"
      echo "xkb_symbols \"caps_f$i\" {"
      echo "    replace key <CAPS> { type = \"ONE_LEVEL\", [ F$i ] };"
      echo "};"
      i=$((i + 1))
    done
  } > "$XKB_SYMBOLS"

  rules_block() {
    echo "// $XKB_MARKER"
    echo "! option = symbols"
    i=1
    while [ "$i" -le 20 ]; do
      echo "  herdr:caps_f$i = +herdr(caps_f$i)"
      i=$((i + 1))
    done
  }

  if [ ! -f "$XKB_RULES" ]; then
    { echo "! include %S/evdev"; echo; rules_block; } > "$XKB_RULES"
  elif ! grep -q "// $XKB_MARKER" "$XKB_RULES"; then
    # Someone else's rules file: add our options, touch nothing else.
    { echo; rules_block; } >> "$XKB_RULES"
  fi
}

# Current xkb-options, one per line.
xkb_options() {
  gsettings get "$GNOME_SCHEMA" xkb-options | grep -o "'[^']*'" | tr -d "'"
}

# Set xkb-options to the given newline-separated list.
xkb_set_options() {
  list=$(printf '%s\n' "$1" | awk 'NF { printf "%s'\''%s'\''", (n++ ? ", " : ""), $0 }')
  gsettings set "$GNOME_SCHEMA" xkb-options "[$list]"
}

# Keep every option except ours, so other keyboard tweaks survive.
xkb_other_options() {
  xkb_options | grep -v '^herdr:' || true
}

xkb_on() {
  xkb_write_files
  others=$(xkb_other_options)
  xkb_set_options "$(printf '%s\nherdr:caps_%s\n' "$others" "$1")"
}

xkb_off() {
  xkb_set_options "$(xkb_other_options)"
}

# Remove the files we generated. A rules file we only appended to keeps
# everything except our block.
xkb_remove_files() {
  if [ -f "$XKB_SYMBOLS" ] && grep -q "$XKB_MARKER" "$XKB_SYMBOLS"; then
    rm -f "$XKB_SYMBOLS"
  fi
  [ -f "$XKB_RULES" ] || return 0
  awk -v marker="// $XKB_MARKER" '
    $0 == marker { skip = 1; next }
    skip && /^!/ && !/^! option = symbols$/ { skip = 0 }
    skip && (/^! option = symbols$/ || /^[[:space:]]*herdr:caps_f/) { next }
    skip { skip = 0 }
    { print }
  ' "$XKB_RULES" > "$XKB_RULES.tmp"
  if ! grep -v -e '^! include %S/evdev$' -e '^[[:space:]]*$' "$XKB_RULES.tmp" | grep -q .; then
    rm -f "$XKB_RULES" "$XKB_RULES.tmp"
  else
    mv "$XKB_RULES.tmp" "$XKB_RULES"
  fi
}
